// TestExtractListenPort pins the listen-address parsing used by the
// systemcontroller self entry so display values stay stable across
// refactors.
func TestExtractListenPort(t *testing.T) {
	cases := []struct {
		addr string
		want string
	}{
		{":5309", "5309"},
		{"0.0.0.0:5309", "5309"},
		{"127.0.0.1:8080", "8080"},
		{"[::1]:5309", "5309"},
		{"", ""},
		{"no-colon", ""},
	}
	for _, tc := range cases {
		if got := extractListenPort(tc.addr); got != tc.want {
			t.Errorf("extractListenPort(%q) = %q, want %q", tc.addr, got, tc.want)
		}
	}
}

