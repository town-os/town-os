func TestHTTPPingIncludesSystemServiceCounts(t *testing.T) {
	c, sd := initSystemServiceTestClient(t)

	sd.Units = []systemd.UnitStatus{
		{Name: systemd.SystemServiceUnitName("node-exporter"), ActiveState: "active"},
		{Name: systemd.SystemServiceUnitName("prometheus"), ActiveState: "active"},
		{Name: systemd.SystemServiceUnitName("monitoring-ui"), ActiveState: "active"},
	}

	ping, err := c.Ping(context.TODO())
	if err != nil {
		t.Fatalf("Ping: %v", err)
	}

	if ping.SystemServices == nil {
		t.Fatal("expected system_services in ping response")
	}

	if ping.SystemServices.Total != 3 {
		t.Fatalf("expected 3 total system services, got %d", ping.SystemServices.Total)
	}

	if ping.SystemServices.Active != 3 {
		t.Fatalf("expected 3 active system services, got %d", ping.SystemServices.Active)
	}
}

// TestHTTPPingExcludesSystemServiceNCAndSocketUnits verifies that network
// controller and socket units generated for system services (via the package
// unit path for prometheus, monitoring-ui, etc.) are not counted in the
// system_services total — only the main service units are.
func TestHTTPPingExcludesSystemServiceNCAndSocketUnits(t *testing.T) {
	c, sd := initSystemServiceTestClient(t)

	sd.Units = []systemd.UnitStatus{
		{Name: systemd.SystemServiceUnitName("node-exporter"), ActiveState: "active"},
		{Name: systemd.SystemServiceUnitName("prometheus"), ActiveState: "active"},
		{Name: "town-os-system--prometheus-network.service", ActiveState: "active"},
		{Name: "town-os-system--prometheus-9090-tcp.socket", ActiveState: "active"},
		{Name: systemd.SystemServiceUnitName("monitoring-ui"), ActiveState: "active"},
		{Name: "town-os-system--monitoring-ui-network.service", ActiveState: "active"},
		{Name: "town-os-system--monitoring-ui-5308-tcp.socket", ActiveState: "active"},
	}

	ping, err := c.Ping(context.TODO())
	if err != nil {
		t.Fatalf("Ping: %v", err)
	}

	if ping.SystemServices == nil {
		t.Fatal("expected system_services in ping response")
	}

	// Only node-exporter, prometheus, monitoring-ui count — not NC or sockets.
	if ping.SystemServices.Total != 3 {
		t.Fatalf("expected 3 total system services (NC and socket units excluded), got %d", ping.SystemServices.Total)
	}
	if ping.SystemServices.Active != 3 {
		t.Fatalf("expected 3 active system services, got %d", ping.SystemServices.Active)
	}
}

