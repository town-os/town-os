func TestHTTPListSystemServicesWithMonitoring(t *testing.T) {
	c, _ := initSystemServiceTestClient(t)

	entries, err := c.ListSystemServices(context.TODO())
	if err != nil {
		t.Fatalf("ListSystemServices: %v", err)
	}

	// Monitoring services (node-exporter, prometheus, monitoring-ui) plus
	// the systemcontroller itself.
	if len(entries) != 4 {
		t.Fatalf("expected 4 entries (node-exporter, prometheus, monitoring-ui, systemcontroller), got %d", len(entries))
	}

	keys := map[string]bool{}
	for _, e := range entries {
		keys[e.Key] = true
		if e.Image == "" {
			t.Fatalf("expected non-empty image for %s", e.Key)
		}
		if e.Port == "" {
			t.Fatalf("expected non-empty port for %s", e.Key)
		}
		if e.DisplayName == "" {
			t.Fatalf("expected non-empty display name for %s", e.Key)
		}
	}

	for _, expected := range []string{"node-exporter", "prometheus", "monitoring-ui", SystemControllerServiceKey} {
		if !keys[expected] {
			t.Fatalf("expected key %q in system services", expected)
		}
	}
}

