func TestHTTPListSystemServicesWithMonitoring(t *testing.T) {
	c, _ := initSystemServiceTestClient(t)

	entries, err := c.ListSystemServices(context.TODO())
	if err != nil {
		t.Fatalf("ListSystemServices: %v", err)
	}

	// All monitoring services: node-exporter, prometheus, monitoring-ui.
	if len(entries) != 3 {
		t.Fatalf("expected 3 entries (node-exporter, prometheus, monitoring-ui), got %d", len(entries))
	}

	keys := map[string]bool{}
	for _, e := range entries {
		keys[e.Key] = true
		if e.Image == "" {
			t.Fatalf("expected non-empty image for %s", e.Key)
		}
		if e.Port == "" {
			t.Fatalf("expected non-empty port for %s", e.Key)
		}
		if e.DisplayName == "" {
			t.Fatalf("expected non-empty display name for %s", e.Key)
		}
	}

	for _, expected := range []string{"node-exporter", "prometheus", "monitoring-ui"} {
		if !keys[expected] {
			t.Fatalf("expected key %q in system services", expected)
		}
	}
}

func TestHTTPListSystemServicesReportsRunningState(t *testing.T) {
	c, sd := initSystemServiceTestClient(t)

	sd.Units = []systemd.UnitStatus{
		{Name: systemd.SystemServiceUnitName("node-exporter"), ActiveState: "active", SubState: "running"},
		{Name: systemd.SystemServiceUnitName("prometheus"), ActiveState: "active", SubState: "running"},
		{Name: systemd.SystemServiceUnitName("monitoring-ui"), ActiveState: "active", SubState: "running"},
	}

	entries, err := c.ListSystemServices(context.TODO())
	if err != nil {
		t.Fatalf("ListSystemServices: %v", err)
	}

	if len(entries) != 3 {
		t.Fatalf("expected 3 entries, got %d", len(entries))
	}

	for _, e := range entries {
		if e.ActiveState != "active" {
			t.Fatalf("expected %s active, got %q", e.Key, e.ActiveState)
		}
	}
}

// TestHTTPListSystemServicesIgnoresNCAndSocketUnits verifies that system
// service NC and socket units (generated by the package unit path for
// monitoring services) are not returned as separate entries from
// ListSystemServices — only the three main service entries are returned.
func TestHTTPListSystemServicesIgnoresNCAndSocketUnits(t *testing.T) {
	c, sd := initSystemServiceTestClient(t)

	sd.Units = []systemd.UnitStatus{
		{Name: systemd.SystemServiceUnitName("node-exporter"), ActiveState: "active"},
		{Name: systemd.SystemServiceUnitName("prometheus"), ActiveState: "active"},
		{Name: "town-os-system--prometheus-network.service", ActiveState: "active"},
		{Name: "town-os-system--prometheus-9090-tcp.socket", ActiveState: "active"},
		{Name: systemd.SystemServiceUnitName("monitoring-ui"), ActiveState: "active"},
		{Name: "town-os-system--monitoring-ui-network.service", ActiveState: "active"},
		{Name: "town-os-system--monitoring-ui-5308-tcp.socket", ActiveState: "active"},
	}

	entries, err := c.ListSystemServices(context.TODO())
	if err != nil {
		t.Fatalf("ListSystemServices: %v", err)
	}

	if len(entries) != 3 {
		t.Fatalf("expected 3 entries (NC and socket units excluded), got %d", len(entries))
	}
	for _, e := range entries {
		if e.Key != "node-exporter" && e.Key != "prometheus" && e.Key != "monitoring-ui" {
			t.Fatalf("unexpected entry key %q", e.Key)
		}
	}
}

func TestHTTPSetSystemServiceStatusStart(t *testing.T) {
	c, sd := initSystemServiceTestClient(t)

	if err := c.SetSystemServiceStatus(context.TODO(), "node-exporter", systemd.Start); err != nil {
		t.Fatalf("SetSystemServiceStatus: %v", err)
	}

	calls := sd.GetCalls()
	found := false
	for _, call := range calls {
		if call.Method == "SetStatus" && len(call.Args) >= 2 {
			if call.Args[0] == systemd.SystemServiceUnitName("node-exporter") && call.Args[1] == systemd.Start {
				found = true
			}
		}
	}
	if !found {
		t.Fatal("expected SetStatus(node-exporter, start) call")
	}
}

