// TestHTTPListSystemServicesIncludesSystemController verifies the
// systemcontroller itself appears in the system services list when the
// SystemControllerImage field is configured, with the key
// SystemControllerServiceKey and the host unit name.
func TestHTTPListSystemServicesIncludesSystemController(t *testing.T) {
	c, sd := initSystemServiceTestClient(t)
	sd.Units = []systemd.UnitStatus{
		{Name: systemd.SystemControllerUnitName, ActiveState: "active", SubState: "running"},
	}

	entries, err := c.ListSystemServices(context.TODO())
	if err != nil {
		t.Fatalf("ListSystemServices: %v", err)
	}

	var sc *SystemServiceEntry
	for i := range entries {
		if entries[i].Key == SystemControllerServiceKey {
			sc = &entries[i]
			break
		}
	}
	if sc == nil {
		t.Fatal("expected systemcontroller entry in system services")
	}
	if sc.DisplayName != "System Controller" {
		t.Fatalf("expected DisplayName 'System Controller', got %q", sc.DisplayName)
	}
	if sc.Image != "quay.io/town/town:test" {
		t.Fatalf("expected image 'quay.io/town/town:test', got %q", sc.Image)
	}
	if sc.Port != "5309" {
		t.Fatalf("expected port '5309', got %q", sc.Port)
	}
	if sc.Name != systemd.SystemControllerUnitName {
		t.Fatalf("expected unit name %q, got %q", systemd.SystemControllerUnitName, sc.Name)
	}
	if sc.ActiveState != "active" {
		t.Fatalf("expected ActiveState 'active', got %q", sc.ActiveState)
	}
}

